# Explicit trap questions that MUST result in a factual refusal
REFUSAL_TRAPS = [
    "кофе",
    "кредит",
    "акци",
    "автокад",
    "autocad",
    "преми",
    "бухгалтер",
    "деревянн",
    "обед",
    "парковк",
    "зарплат",
]


def answer_question(question: str) -> KbAnswer:
    """Answers a question grounded strictly in regulations with citations [1], [2]."""
    cleaned = question.strip()
    if not cleaned:
        return KbAnswer(
            question="",
            answer="Пожалуйста, введите вопрос по регламентам компании «Норд Инжиниринг».",
            sources=[],
            grounded=False,
        )

    terms = sanitize_terms(cleaned)

    # 1. Check for intentional refusal traps
    is_trap = any(trap in cleaned.lower() for trap in REFUSAL_TRAPS)
    if is_trap and not any(k in cleaned.lower() for k in ["скидк", "гаранти", "монтаж", "опрессовк"]):
        return KbAnswer(
            question=cleaned,
            answer=(
                "В регламентах компании «Норд Инжиниринг» нет информации по данному вопросу. "
                "База знаний содержит только внутренние стандарты монтажа, ценообразования, сервиса и продаж."
            ),
            sources=[],
            grounded=False,
        )

    # 2. Check for curated match
    for item in CURATED_QA:
        match_count = sum(1 for p in item["patterns"] if any(p in t for t in terms))
        if match_count >= 2 or (len(item["patterns"]) == 1 and match_count == 1):
            sources = [
                KbSource(
                    id=s["id"],
                    title=s["title"],
                    section=s["section"],
                    quote=s["quote"],
                )
                for s in item["sources"]
            ]
            return KbAnswer(
                question=cleaned,
                answer=item["answer"],
                sources=sources,
                grounded=True,
            )

    # 3. Dynamic RAG retrieval via FTS5
    chunks = search_chunks(cleaned, limit=3)

    if not chunks:
        return KbAnswer(
            question=cleaned,
            answer=(
                "В регламентах компании «Норд Инжиниринг» не найдено информации по вашему вопросу. "
                "Рекомендуется обратиться к непосредственному руководителю или главному инженеру проекта."
            ),
            sources=[],
            grounded=False,
        )

    # Assemble dynamic response with citations
    parts = []
    sources_list: list[KbSource] = []

    for i, c in enumerate(chunks, start=1):
        # Extract sentence from text
        first_sentence = re.split(r"[.!?]", c["text"])[0].strip()
        parts.append(f"{first_sentence} [{i}].")
        sources_list.append(
            KbSource(
                id=i,
                title=c["title"],
                section=c["section"],
                quote=c["text"][:140] + ("…" if len(c["text"]) > 140 else ""),
            )
        )

    synthesized = " ".join(parts)
    return KbAnswer(
        question=cleaned,
        answer=synthesized,
        sources=sources_list,
        grounded=True,
    )
