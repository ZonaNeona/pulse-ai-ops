"""Ports. `B24Transport` speaks raw Bitrix24 REST; `CrmPort` speaks the domain.

The emulator and the live portal both implement `B24Transport`, so everything above it — paging,
mapping, sync, modules — runs the same code in the demo and against a real portal.
"""

from datetime import datetime
from typing import Any, Protocol

from pulse.crm.model import Call, Company, Deal, Funnel, Lead, StageChange, Task, User


class B24Transport(Protocol):
    async def call(self, method: str, params: dict[str, Any] | None = None) -> dict[str, Any]: ...


class CrmPort(Protocol):
    async def users(self) -> list[User]: ...
    async def funnels(self) -> list[Funnel]: ...
    async def companies(self) -> list[Company]: ...
    async def deals(self) -> list[Deal]: ...
    async def leads(self) -> list[Lead]: ...
    async def calls(self, since: datetime) -> list[Call]: ...
    async def tasks(self) -> list[Task]: ...
    async def stage_history(self, since: datetime) -> list[StageChange]: ...
